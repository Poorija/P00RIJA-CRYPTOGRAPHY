package com.p00rija.cryptography

import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import android.util.Base64
import java.security.KeyStore
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/**
 * Holds the master password for biometric quick unlock.
 *
 * The secret is encrypted with an AES key that lives inside the Android
 * Keystore and never leaves it -- on most handsets it never leaves the secure
 * element at all. The key is created with setUserAuthenticationRequired(true),
 * so the operating system refuses to decrypt with it until the user has
 * presented a face or a finger. That refusal is enforced by the platform, not
 * by this app: a rooted phone reading the ciphertext out of app storage still
 * has nothing, because the key that opens it is not in app storage.
 *
 * setInvalidatedByBiometricEnrolment means enrolling a new fingerprint
 * destroys the key, and with it the stored password. That is the intended
 * behaviour: a new finger is a new person until the real owner types the
 * password again.
 *
 * Rust calls these four methods through JNI. They take and return plain
 * strings because that is the cheapest thing to pass across that boundary.
 */
object SecureStore {

    private const val KEY_ALIAS = "p00rija_quick_unlock_v1"
    private const val PREFS = "p00rija_secure_store"
    private const val CIPHERTEXT = "quick_unlock_blob"
    private const val TRANSFORM = "AES/GCM/NoPadding"
    private const val TAG_BITS = 128
    /** How long a satisfied prompt keeps the key usable. */
    private const val WINDOW_SECONDS = 30

    /**
     * Hands the virtual machine and the Activity to the Rust side.
     *
     * Rust cannot find them on its own here: ndk-context, the usual
     * answer, is never populated in a Tauri app and panics when asked.
     * Calling in from Kotlin is the direction Android already supports,
     * and once is enough for the life of the process.
     */
    @JvmStatic
    external fun nativeRegister(context: android.content.Context)

    /** Whether a password is currently stored. */
    @JvmStatic
    fun hasSecret(context: android.content.Context): Boolean =
        context.getSharedPreferences(PREFS, android.content.Context.MODE_PRIVATE)
            .contains(CIPHERTEXT) && keyExists()

    /**
     * Encrypts and stores the password. Returns an empty string on success and
     * the failure's message otherwise, so the Rust side needs no exception
     * handling across JNI.
     */
    @JvmStatic
    fun store(context: android.content.Context, secret: String): String = try {
        val key = createKey()
        val cipher = Cipher.getInstance(TRANSFORM)
        cipher.init(Cipher.ENCRYPT_MODE, key)
        val body = cipher.doFinal(secret.toByteArray(Charsets.UTF_8))
        // The IV is generated by the cipher and is not secret; it is kept
        // beside the ciphertext because GCM needs it back to decrypt.
        val blob = Base64.encodeToString(cipher.iv, Base64.NO_WRAP) + ":" +
            Base64.encodeToString(body, Base64.NO_WRAP)
        context.getSharedPreferences(PREFS, android.content.Context.MODE_PRIVATE)
            .edit().putString(CIPHERTEXT, blob).apply()
        ""
    } catch (error: Throwable) {
        error.message ?: error.javaClass.simpleName
    }

    /**
     * Returns the stored password, or an empty string when there is nothing to
     * return or the key refuses.
     *
     * The caller must have satisfied the biometric prompt immediately before
     * this: the Keystore key is authentication-bound, so init() throws
     * UserNotAuthenticatedException outside that window and this returns
     * nothing rather than pretending.
     */
    @JvmStatic
    fun retrieve(context: android.content.Context): String {
        return try {
            val blob = context.getSharedPreferences(PREFS, android.content.Context.MODE_PRIVATE)
                .getString(CIPHERTEXT, null) ?: ""
            val parts = blob.split(":")
            if (parts.size != 2) {
                ""
            } else {
                val iv = Base64.decode(parts[0], Base64.NO_WRAP)
                val body = Base64.decode(parts[1], Base64.NO_WRAP)
                val store = KeyStore.getInstance("AndroidKeyStore").apply { load(null) }
                val key = store.getKey(KEY_ALIAS, null) as? SecretKey
                if (key == null) {
                    ""
                } else {
                    val cipher = Cipher.getInstance(TRANSFORM)
                    cipher.init(Cipher.DECRYPT_MODE, key, GCMParameterSpec(TAG_BITS, iv))
                    String(cipher.doFinal(body), Charsets.UTF_8)
                }
            }
        } catch (error: Throwable) {
            /* An unsatisfied prompt arrives here as UserNotAuthenticatedException
               and an invalidated key as KeyPermanentlyInvalidatedException. Both
               mean the same thing to the caller -- nothing came back -- and both
               are answered by asking for the password instead. */
            ""
        }
    }

    /** Forgets the password and the key that opens it. */
    @JvmStatic
    fun clear(context: android.content.Context): String = try {
        context.getSharedPreferences(PREFS, android.content.Context.MODE_PRIVATE)
            .edit().remove(CIPHERTEXT).apply()
        KeyStore.getInstance("AndroidKeyStore").apply { load(null) }.deleteEntry(KEY_ALIAS)
        ""
    } catch (error: Throwable) {
        error.message ?: error.javaClass.simpleName
    }

    private fun keyExists(): Boolean = try {
        KeyStore.getInstance("AndroidKeyStore").apply { load(null) }.containsAlias(KEY_ALIAS)
    } catch (error: Throwable) {
        false
    }

    private fun createKey(): SecretKey {
        val generator = KeyGenerator.getInstance(
            KeyProperties.KEY_ALGORITHM_AES, "AndroidKeyStore"
        )
        val spec = KeyGenParameterSpec.Builder(
            KEY_ALIAS,
            KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT
        )
            .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
            .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
            .setUserAuthenticationRequired(true)
            .setInvalidatedByBiometricEnrollment(true)
            .apply {
                /* A time-bound key is unusable in BOTH directions until the
                   window is open: encrypting throws UserNotAuthenticated just
                   as decrypting does. So the caller satisfies the prompt before
                   storing as well as before reading -- which also proves the
                   sensor works before anything starts depending on it.

                   How the window is declared changed at API 30:
                   before it, a time-based window is opened by the keyguard --
                   a PIN, pattern or password -- and a fingerprint alone may
                   not satisfy it, which is why every authenticate() call this
                   app makes passes allowDeviceCredential. From API 30 a strong
                   biometric opens it directly. */
                if (android.os.Build.VERSION.SDK_INT >= android.os.Build.VERSION_CODES.R) {
                    setUserAuthenticationParameters(
                        WINDOW_SECONDS,
                        KeyProperties.AUTH_BIOMETRIC_STRONG or KeyProperties.AUTH_DEVICE_CREDENTIAL
                    )
                } else {
                    @Suppress("DEPRECATION")
                    setUserAuthenticationValidityDurationSeconds(WINDOW_SECONDS)
                }
            }
            .build()
        generator.init(spec)
        return generator.generateKey()
    }
}
