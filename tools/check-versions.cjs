/* One release, five places that state its version, and nothing that made them
   agree. The audit found js/app.js still saying 2.99.91 while package.json had
   moved to 2.99.92 — so the About screen told users a version the build was
   not. Each of these is read by something different (the About screen, npm,
   the macOS bundle's Info.plist, the two Tauri configs), which is why they
   drift quietly and why only a check catches it.

   The asset tag in index.html is deliberately NOT compared: it carries a
   suffix (2.99.94-audit-v1) because it exists to bust caches, not to name a
   release. Its numeric part is checked against the rest. */
const fs = require('fs');
const path = require('path');
const ROOT = path.resolve(__dirname, '..');
const read = (p) => fs.readFileSync(path.join(ROOT, p), 'utf8');

/* The mobile projects are only present once `tauri ios init` / `android init`
   has run, so a clone that has never built them is not a drift. */
const exists = (file) => fs.existsSync(path.join(ROOT, file));
const found = {
  'package.json': JSON.parse(read('package.json')).version,
  'src-tauri/tauri.conf.json': JSON.parse(read('src-tauri/tauri.conf.json')).version,
  'src-tauri/tauri.monitor.conf.json': JSON.parse(read('src-tauri/tauri.monitor.conf.json')).version,
  'src-tauri/Cargo.toml': (/^version = "([^"]+)"/m.exec(read('src-tauri/Cargo.toml')) || [])[1],
  /* The published npm package carries its own manifest and is what a user
     gets from `npx p00rija-cryptography`. It shipped at 2.26.90 while the app
     said 2.26.95, which is exactly the drift this file exists to catch. */
  'npm-package/package.json': JSON.parse(read('npm-package/package.json')).version,
  /* The standalone relay is deployed on its own and its protocol moves with
     the app: presence-state, the app-awake liveness rule and the per-device
     push language all shipped in 2.26.95. It was still claiming 2.99.91 — the
     audit named this and left the decision open; the answer is that a relay
     which speaks this release's protocol should say so. */
  'standalone-relay/package.json': JSON.parse(read('standalone-relay/package.json')).version,
  /* The two mobile projects. Neither was checked, and iOS had been sitting at
     2.99.90 while everything else moved to 2.26.95 — a version somebody
     installing a TestFlight build would read off the About screen and quote
     back in a bug report. They are generated by `tauri ios init` /
     `android init` and then edited by hand, so nothing regenerates them on a
     version bump; being in this list is what makes the drift visible. */
  ...(exists('src-tauri/gen/apple/project.yml') ? {
    'src-tauri/gen/apple/project.yml': (/CFBundleShortVersionString:\s*([0-9][0-9A-Za-z.\-]*)/
      .exec(read('src-tauri/gen/apple/project.yml')) || [])[1],
  } : {}),
  ...(exists('src-tauri/gen/android/app/tauri.properties') ? {
    'src-tauri/gen/android/app/tauri.properties': (/tauri\.android\.versionName=([0-9][0-9A-Za-z.\-]*)/
      .exec(read('src-tauri/gen/android/app/tauri.properties')) || [])[1],
  } : {}),
  'js/app.js APP_VERSION_SEMVER': (/APP_VERSION_SEMVER = '([^']+)'/.exec(read('js/app.js')) || [])[1],
};

const tagMatch = /\?v=(\d+\.\d+\.\d+)(-[\w.-]+)?/.exec(read('index.html')) || [];
const tag = tagMatch[1];
if (tag) found['index.html asset tag'] = tag;

const values = new Set(Object.values(found));

/* The asset tag is the semver plus a build suffix — 2.99.97-nocam-v1 — and it
   is a SEPARATE string from every version above. index.html, sw.js and
   js/app.js must carry the same one: the service worker registers
   ./sw.js?v=<tag>, caches under a name built from it, and reloads once per
   tag, so two of them disagreeing means the worker either never updates or
   reloads forever.
   This checked the semver alone and passed while js/app.js still carried the
   previous tag. Nothing local objected; the server's own guard stopped the
   deployment after the files had already been copied. */
const fullTag = tagMatch[0] ? tagMatch[0].replace('?v=', '') : '';
if (fullTag) {
  const assetTags = new Set([...read('index.html').matchAll(/\?v=(\d+\.\d+\.\d+-[\w.-]+)/g)].map((m) => m[1]));
  if (assetTags.size !== 1) {
    console.error('Mixed asset builds in index.html:', [...assetTags]);
    process.exit(1);
  }
  const carries = {
    'index.html': read('index.html').includes(`?v=${fullTag}`),
    'sw.js': read('sw.js').includes(fullTag),
    'js/app.js': read('js/app.js').includes(fullTag),
  };
  /* The About screen's own copy. js/app.js derives APP_BUILD_TAG from this
     file's ?v= at runtime, so it cannot drift on a real page — but it keeps a
     literal for contexts with no script URL, and a stale literal there is what
     made a build served as chat-v12 introduce itself as chat-v11 on the one
     screen people are asked to read when they report a bug. */
  const suffix = fullTag.includes('-') ? fullTag.slice(fullTag.indexOf('-') + 1) : '';
  for (const manifest of ['package.json', 'npm-package/package.json', 'standalone-relay/package.json']) {
    carries[manifest + ' buildTag'] = JSON.parse(read(manifest)).buildTag === suffix;
  }
  const fallback = (/return '([A-Za-z0-9._-]+)';\s*\}\)\(\);/.exec(read('js/app.js')) || [])[1];
  if (suffix) carries[`js/app.js APP_BUILD_TAG fallback (${fallback || 'not found'})`] = fallback === suffix;
  /* The service worker's registration URL. It is a separate literal from
     everything above and it drifted the longest: js/app.js registered
     ./sw.js?v=2.104.0-chat-v3 while the build served 2.26.95-chat-v42, so the
     URL the browser keys the worker on had not changed in dozens of releases
     and only a byte difference in sw.js still made an update land. Nothing
     caught it, because the check above asks whether THIS FILE mentions the tag
     anywhere and the one-time reload key already did. */
  const swRegistration = (/serviceWorker\.register\('\.\/sw\.js\?v=([^']+)'/.exec(read('js/app.js')) || [])[1];
  carries[`js/app.js service worker registration (${swRegistration || 'not found'})`] = swRegistration === fullTag;
  const behind = Object.entries(carries).filter(([, ok]) => !ok).map(([where]) => where);
  console.log(`\n  asset tag ${fullTag}`);
  Object.entries(carries).forEach(([where, ok]) => console.log(`  ${ok ? 'ok  ' : 'MISSING'} ${where}`));
  if (behind.length) {
    console.error(`\n  ${behind.join(', ')} do not carry the asset tag ${fullTag}.`);
    console.error('  The service worker keys its cache, its registration and its one-time');
    console.error('  reload on this string, so all three files must agree.');
    process.exit(1);
  }
}
Object.entries(found).forEach(([where, value]) => {
  console.log(`  ${String(value).padEnd(10)} ${where}`);
});

if (values.size === 1) {
  console.log(`\n  all ${Object.keys(found).length} declarations agree on ${[...values][0]}`);
  process.exit(0);
}
console.error(`\n  ${values.size} different versions are declared: ${[...values].join(', ')}`);
console.error('  They must match, or the app reports a version it is not.');
process.exit(1);
